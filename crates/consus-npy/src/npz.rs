//! Named NPY arrays stored in ZIP archives.

use std::io::{Cursor, Read, Seek, Write};

use consus_zip::{Method, ZipReader, ZipWriter};

use crate::{NpyArray, NpyElement, Result, read_npy, write_npy};

/// The archive member that holds array `name`: NumPy appends `.npy`.
fn member_name(name: &str) -> String {
    if name.ends_with(".npy") {
        name.to_owned()
    } else {
        format!("{name}.npy")
    }
}

/// Typed NPZ archive reader.
pub struct NpzReader<R: Read + Seek> {
    archive: ZipReader<R>,
}

impl<R: Read + Seek> NpzReader<R> {
    /// Opens an NPZ archive.
    pub fn new(reader: R) -> Result<Self> {
        Ok(Self {
            archive: ZipReader::new(reader)?,
        })
    }

    /// Reads a named NPY member.
    pub fn by_name<T: NpyElement>(&mut self, name: &str) -> Result<NpyArray<T>> {
        let bytes = self.archive.read_by_name(&member_name(name))?;
        read_npy(Cursor::new(bytes))
    }
}

/// Typed NPZ archive writer.
///
/// Members are DEFLATE-compressed, matching `numpy.savez_compressed`.
pub struct NpzWriter<W: Write> {
    archive: ZipWriter<W>,
}

impl<W: Write> NpzWriter<W> {
    /// Creates an NPZ archive writer.
    pub fn new(writer: W) -> Self {
        Self {
            archive: ZipWriter::new(writer),
        }
    }

    /// Adds a named typed array.
    pub fn add_array<T: NpyElement>(&mut self, name: &str, array: &NpyArray<T>) -> Result<()> {
        let mut bytes = Vec::new();
        write_npy(&mut bytes, array)?;
        self.archive
            .add_entry(&member_name(name), &bytes, Method::Deflated)?;
        Ok(())
    }

    /// Finishes the ZIP central directory and returns the writer.
    pub fn finish(self) -> Result<W> {
        Ok(self.archive.finish()?)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn archive_round_trip_is_name_and_value_semantic() {
        let array = NpyArray::new([3], [2_i64, 1, 1]).unwrap();
        let mut writer = NpzWriter::new(Cursor::new(Vec::new()));
        writer.add_array("focus_idx", &array).unwrap();
        let bytes = writer.finish().unwrap().into_inner();
        let mut reader = NpzReader::new(Cursor::new(bytes)).unwrap();
        assert_eq!(reader.by_name::<i64>("focus_idx").unwrap(), array);
    }

    /// `numpy.savez` (stored members) and `numpy.savez_compressed` (DEFLATE
    /// members) of `a = arange(6, dtype='<i8').reshape(2, 3)` and
    /// `b = [1.5, -2.0]`, generated by `tests/data/generate_npz_fixtures.py`.
    #[test]
    fn reads_numpy_generated_archives() {
        for bytes in [
            &include_bytes!("../tests/data/numpy_savez.npz")[..],
            &include_bytes!("../tests/data/numpy_savez_compressed.npz")[..],
        ] {
            let mut reader = NpzReader::new(Cursor::new(bytes)).unwrap();
            let a = reader.by_name::<i64>("a").unwrap();
            assert_eq!(a.shape(), [2, 3]);
            assert_eq!(a.values(), [0, 1, 2, 3, 4, 5]);
            let b = reader.by_name::<f64>("b.npy").unwrap();
            assert_eq!(b.shape(), [2]);
            assert_eq!(b.values(), [1.5, -2.0]);
        }
    }

    #[test]
    fn missing_array_is_a_typed_zip_error() {
        let mut writer = NpzWriter::new(Vec::new());
        writer
            .add_array("a", &NpyArray::new([1], [1_i64]).unwrap())
            .unwrap();
        let mut reader = NpzReader::new(Cursor::new(writer.finish().unwrap())).unwrap();
        let err = reader.by_name::<i64>("absent").unwrap_err();
        assert!(
            matches!(&err, crate::Error::Zip(consus_zip::Error::MissingEntry { name }) if name == "absent.npy"),
            "{err:?}"
        );
    }
}
