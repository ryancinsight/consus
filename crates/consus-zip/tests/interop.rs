//! Archives written by other implementations decode to their known members.

use std::io::Cursor;

use consus_zip::{Method, ZipReader, ZipWriter};

/// Written by the `zip` crate 9.0.5; see `data/generate_zip_crate_fixture.rs`.
#[test]
fn reads_zip_crate_archive() {
    let bytes = include_bytes!("data/zip_crate.zip");
    let mut reader = ZipReader::new(Cursor::new(&bytes[..])).unwrap();
    let summary: Vec<(&str, Method, u64)> = reader
        .entries()
        .iter()
        .map(|e| (e.name(), e.method(), e.uncompressed_size()))
        .collect();
    assert_eq!(
        summary,
        [
            ("stored.txt", Method::Stored, 24),
            ("dir/deflated.bin", Method::Deflated, 4096),
            ("ünïcode.txt", Method::Deflated, 2),
        ]
    );
    assert_eq!(
        reader.read_by_name("stored.txt").unwrap(),
        b"written by the zip crate"
    );
    let pattern: Vec<u8> = (0..4096u32).map(|i| u8::try_from(i % 7).unwrap()).collect();
    assert_eq!(reader.read_by_name("dir/deflated.bin").unwrap(), pattern);
    assert_eq!(reader.read_by_name("ünïcode.txt").unwrap(), "ä".as_bytes());
}

/// NumPy `savez` and `savez_compressed` archives, generated by
/// `crates/consus-npy/tests/data/generate_npz_fixtures.py`: every member
/// passes its CRC-32 check and carries the NPY magic.
#[test]
fn reads_numpy_archives() {
    for bytes in [
        &include_bytes!("../../consus-npy/tests/data/numpy_savez.npz")[..],
        &include_bytes!("../../consus-npy/tests/data/numpy_savez_compressed.npz")[..],
    ] {
        let mut reader = ZipReader::new(Cursor::new(bytes)).unwrap();
        let names: Vec<String> = reader
            .entries()
            .iter()
            .map(|e| e.name().to_owned())
            .collect();
        assert_eq!(names, ["a.npy", "b.npy"]);
        for index in 0..2 {
            let member = reader.read_entry(index).unwrap();
            assert_eq!(&member[..6], b"\x93NUMPY");
        }
    }
}

/// The writer's output re-opens through the reader with identical entries,
/// which pins the central directory the writer emits to the one it parses.
#[test]
fn written_archive_reports_the_written_entries() {
    let mut writer = ZipWriter::new(Vec::new());
    writer
        .add_entry("x.npy", &[1, 2, 3], Method::Stored)
        .unwrap();
    writer
        .add_entry("y.npy", &[4; 100], Method::Deflated)
        .unwrap();
    let mut reader = ZipReader::new(Cursor::new(writer.finish().unwrap())).unwrap();
    assert_eq!(reader.entries()[0].method(), Method::Stored);
    assert_eq!(reader.entries()[1].uncompressed_size(), 100);
    assert_eq!(reader.read_by_name("y.npy").unwrap(), vec![4; 100]);
}
